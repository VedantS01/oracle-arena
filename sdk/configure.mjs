// Generate assembly/config.ts from a function id and a password.
// Usage: node configure.mjs <function_id 0-9> <password>
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const [, , idStr, password] = process.argv;
const id = Number(idStr);

if (!Number.isInteger(id) || id < 0 || id > 9 || password === undefined) {
  console.error("Usage: node configure.mjs <function_id 0-9> <password>");
  process.exit(1);
}

const bytes = [...new TextEncoder().encode(password)];
if (bytes.length > 255) {
  console.error("Password must be at most 255 bytes.");
  process.exit(1);
}
const hex = bytes.map((b) => "0x" + b.toString(16).padStart(2, "0")).join(",");

const out = `// Generated by \`node configure.mjs ${id} <password>\`.
// Baseline (Level-1) defense: the expected password bytes are visible here.
// Harden before you ship — hash the password, derive the selector from it,
// obfuscate, or interpret a bytecode VM. Only the ABI is fixed.

export const FUNCTION_ID: i32 = ${id};
export const EXPECTED: usize = memory.data<u8>([${hex}]);
export const EXPECTED_LEN: i32 = ${bytes.length};
`;

const dir = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(dir, "assembly", "config.ts"), out);
console.log(`config.ts written: function_id=${id}, password length=${bytes.length} bytes`);
